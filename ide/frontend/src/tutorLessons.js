export function lessonFor(page) {
  const authored = TUTOR_LESSONS[page?.id]
  if (authored) return authored
  if (!page) return null
  return {
    title: page.title,
    intro: page.definition,
    example: page.examples?.[0] || '# Read the concept in the Codex, then make your own small example.',
    explain: page.when_to_use || 'Read the example one line at a time and predict what changes.',
    try: 'Open practice and write a small example in a different setting. Run it and change one input.',
    teachback: page.check_prompt || 'Explain this idea in your own words.',
    transfer: 'Where could you use this idea in a different kind of program?',
    mistake: page.common_mistakes?.[0] || 'Check a normal input and an edge case.',
  }
}

