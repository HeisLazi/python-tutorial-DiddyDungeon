"""Worn charms: every trinket shown on the hero in combat, made from its own icon.

A trinket used to appear on the hero only if it was one of three hand-drawn charms. Each of the 64 trinkets now has a
tiny charm (about 10 px) cut from its icon in `ide/frontend/public/campaign-art/items/trinket-<id>.png`:
the object is cropped, shrunk to fit, given a dark 1px outline and lifted a little so it reads on a dark coat.

Writes:
  art/charm-<slug>.png               the worn sprite (slug = the trinket's name, lower-case, non-letters as '-')
  charms_registry.gd                 the slugs Godot loads
  ide/frontend/src/trinketCharms.js  the same slugs for hunterAppearance()

Run:  python3 prototypes/godot-combat/source-art/charms.py   (it asks .venv/bin/python for the trinket names)
Then `godot --headless --path prototypes/godot-combat --import`.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

import numpy as np
from PIL import Image

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
ART = HERE.parent / "art"
ICONS = REPO / "ide" / "frontend" / "public" / "campaign-art" / "items"
SIZE = 9  # the object's longest side; the outline adds a pixel on each side
OUTLINE = (24, 18, 30, 255)


def slug(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def charm(icon: Image.Image) -> Image.Image:
    icon = icon.convert("RGBA")
    box = icon.getbbox()
    icon = icon.crop(box)
    scale = SIZE / max(icon.size)
    small = icon.resize((max(1, round(icon.width * scale)), max(1, round(icon.height * scale))), Image.BOX)
    a = np.array(small).astype(float)
    a[:, :, 3] = np.where(a[:, :, 3] >= 110, 255, 0)
    rgb = a[:, :, :3] / 255.0
    # Lift and saturate a little: a charm is a few pixels and sits on a dark coat.
    lum = rgb.mean(axis=2, keepdims=True)
    rgb = np.clip(lum + (rgb - lum) * 1.25, 0, 1) ** 0.8
    a[:, :, :3] = rgb * 255
    body = Image.fromarray(a.astype(np.uint8), "RGBA")
    solid = np.pad(np.array(body)[:, :, 3] > 0, 1)  # one pixel of room all round for the outline
    grown = solid | np.roll(solid, 1, 0) | np.roll(solid, -1, 0) | np.roll(solid, 1, 1) | np.roll(solid, -1, 1)
    ring = np.zeros(solid.shape + (4,), np.uint8)
    ring[grown & ~solid] = OUTLINE
    out = Image.fromarray(ring, "RGBA")
    out.alpha_composite(body, (1, 1))
    return out


def trinket_names() -> dict[str, str]:
    """{trinket id: name}. The catalog needs the project's own Python (fastapi, pydantic), so ask it."""
    import json
    import subprocess

    code = "import json;from ide.server.state import armory_catalog;print(json.dumps({i['id']: i['name'] for i in armory_catalog().values() if i['slot'] == 'trinket'}))"
    python = REPO / ".venv" / "bin" / "python"
    out = subprocess.run([str(python if python.exists() else sys.executable), "-c", code], cwd=REPO, capture_output=True, text=True, check=True).stdout
    return json.loads(out)


def main() -> None:
    names = trinket_names()
    slugs = []
    for item_id, item_name in names.items():
        icon_path = ICONS / f"trinket-{item_id}.png"
        if not icon_path.exists():
            print(f"skip {item_name}: no icon yet", file=sys.stderr)
            continue
        name = slug(item_name)
        charm(Image.open(icon_path)).save(ART / f"charm-{name}.png")
        slugs.append(name)
    slugs.sort()
    (HERE.parent / "charms_registry.gd").write_text(
        "extends RefCounted\n## Generated by source-art/charms.py. Every trinket that has a worn charm, as art/charm-<slug>.png.\n"
        "const SLUGS := [\n" + "".join(f'\t"{name}",\n' for name in slugs) + "]\n"
    )
    (REPO / "ide" / "frontend" / "src" / "trinketCharms.js").write_text(
        "// Generated by prototypes/godot-combat/source-art/charms.py. Trinkets with a worn charm in the combat scene.\n"
        "export const TRINKET_CHARMS = new Set([\n" + "".join(f"  '{name}',\n" for name in slugs) + "])\n\n"
        "export const trinketSlug = (name) => String(name || '').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')\n"
    )
    print(f"{len(slugs)} charms")


if __name__ == "__main__":
    main()
